function ultraArtworkYear(art) {
    const date = art.date || "";
    const nums = date.match(/\d{3,4}/g);
    if (!nums) return 0;
    let year = Number(nums[0]);
    if (/BCE/i.test(date)) year = -year;
    return year;
}
function ultraFormatYear(year) { return year < 0 ? `${Math.abs(year)} BCE` : `${year}`; }

function initUltraTimeline() {
    const rail = getElement("ultraTimelineRail");
    if (!rail) return;
    const list = Object.values(artworks)
        .map(art => ({ art, year: ultraArtworkYear(art) }))
        .sort((a, b) => a.year - b.year);
    const min = Math.min(...list.map(x => x.year));
    const max = Math.max(...list.map(x => x.year));
    rail.innerHTML = "";

    const railWidth = Math.max(900, rail.clientWidth || 1200);
    const laneGap = 14;
    const rowHeight = 58;
    const lanes = [];

    list.forEach(({ art, year }) => {
        const pos = ((year - min) / Math.max(1, (max - min))) * 100;
        const clampedPos = Math.max(1, Math.min(99, pos));
        const centerX = (clampedPos / 100) * railWidth;
        const labelWidth = Math.max(110, Math.min(170, art.title.length * 6.5 + 28));
        const leftEdge = centerX - labelWidth / 2;
        const rightEdge = centerX + labelWidth / 2;

        let laneIndex = lanes.findIndex(lastRight => leftEdge > lastRight + laneGap);
        if (laneIndex === -1) {
            laneIndex = lanes.length;
            lanes.push(rightEdge);
        } else {
            lanes[laneIndex] = rightEdge;
        }

        const button = document.createElement("button");
        button.type = "button";
        button.className = "timeline-art-point";
        button.style.left = `${clampedPos}%`;
        button.style.setProperty("--timeline-width", `${labelWidth}px`);
        button.style.setProperty("--timeline-label-top", `${22 + laneIndex * rowHeight}px`);
        button.innerHTML = `<i></i><strong>${art.title}</strong><span>${ultraFormatYear(year)}</span>`;
        button.setAttribute("aria-label", `${art.title}, ${ultraFormatYear(year)}`);
        button.addEventListener("click", () => openFromExplorer(art.id));
        rail.appendChild(button);
    });

    rail.style.height = `${Math.max(260, 78 + lanes.length * rowHeight)}px`;
}
