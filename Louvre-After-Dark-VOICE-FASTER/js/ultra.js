function ultraCommonsPage(art) {
    const url = art?.image || "";
    const marker = "/Special:Redirect/file/";
    const i = url.indexOf(marker);
    if (i < 0) return "https://commons.wikimedia.org/";
    const name = url.slice(i + marker.length).split("?")[0];
    return `https://commons.wikimedia.org/wiki/File:${name}`;
}

