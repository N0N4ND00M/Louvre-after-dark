function initUltraAccessibilityHub() {
    if(getElement("ladAccessibility")) return;
    const wrap=document.createElement("div"); wrap.id="ladAccessibility"; wrap.className="lad-accessibility";
    wrap.innerHTML=`<button id="a11yTrigger" type="button" aria-expanded="false">A11Y</button><div class="a11y-panel" hidden><strong>ACCESSIBILITY</strong><label><input type="checkbox" data-a11y="motion"> Reduce motion</label><label><input type="checkbox" data-a11y="contrast"> High contrast</label><label><input type="checkbox" data-a11y="text"> Larger text</label><button id="a11yReset" type="button">RESET</button></div>`;
    document.body.appendChild(wrap);
    const panel=wrap.querySelector(".a11y-panel"), trigger=getElement("a11yTrigger");
    const load=()=>{try{return JSON.parse(localStorage.getItem("lad-a11y-v1")||"{}")}catch{return{}}};
    const state=load();
    const apply=()=>{
        document.body.classList.toggle("user-reduced-motion",!!state.motion);
        document.body.classList.toggle("user-high-contrast",!!state.contrast);
        document.body.classList.toggle("user-large-text",!!state.text);
        wrap.querySelectorAll("[data-a11y]").forEach(i=>i.checked=!!state[i.dataset.a11y]);
        try{localStorage.setItem("lad-a11y-v1",JSON.stringify(state))}catch{}
    };
    trigger?.addEventListener("click",()=>{const open=panel.hidden;panel.hidden=!open;trigger.setAttribute("aria-expanded",String(open))});
    wrap.querySelectorAll("[data-a11y]").forEach(i=>i.addEventListener("change",()=>{state[i.dataset.a11y]=i.checked;apply()}));
    getElement("a11yReset")?.addEventListener("click",()=>{state.motion=state.contrast=state.text=false;apply()});
    apply();
}

