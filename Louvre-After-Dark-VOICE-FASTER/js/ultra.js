function initUltraCommandPalette() {
    if(getElement("ladCommandPalette")) return;
    const wrap=document.createElement("div");
    wrap.id="ladCommandPalette"; wrap.className="lad-command-palette"; wrap.setAttribute("aria-hidden","true");
    wrap.innerHTML=`<div class="command-backdrop"></div><div class="command-panel" role="dialog" aria-modal="true" aria-label="Quick navigation"><div class="command-search-row"><span>⌘K</span><input id="commandInput" type="search" placeholder="Search artworks or jump to a page…" autocomplete="off"><button id="commandClose" type="button">ESC</button></div><div id="commandResults" class="command-results"></div><small class="command-help">↑ ↓ navigate · ENTER open · ESC close</small></div>`;
    document.body.appendChild(wrap);
    const trigger=document.createElement("button"); trigger.className="command-trigger"; trigger.type="button"; trigger.innerHTML="⌘K <span>SEARCH</span>"; trigger.setAttribute("aria-label","Open quick search"); document.body.appendChild(trigger);
    const input=getElement("commandInput"), results=getElement("commandResults");
    let activeIndex=0, current=[];
    const pages=[
        {label:"Home",sub:"Main entrance",url:"index.html"},
        {label:"Exhibitions",sub:"24-work night archive",url:"exhibitions.html"},
        {label:"Workshop",sub:"Conservation laboratory",url:"workshop.html"},
        {label:"Analysis",sub:"Project documentation",url:"analysis.html"}
    ];
    const open=()=>{wrap.classList.add("open");wrap.setAttribute("aria-hidden","false");render("");setTimeout(()=>input?.focus(),20)};
    const close=()=>{wrap.classList.remove("open");wrap.setAttribute("aria-hidden","true")};
    const select=i=>{activeIndex=Math.max(0,Math.min(current.length-1,i));results?.querySelectorAll("button").forEach((b,j)=>b.classList.toggle("active",j===activeIndex));results?.querySelectorAll("button")[activeIndex]?.scrollIntoView({block:"nearest"});};
    const render=query=>{
        const q=query.trim().toLowerCase();
        const pageItems=pages.filter(p=>!q||`${p.label} ${p.sub}`.toLowerCase().includes(q)).map(p=>({...p,type:"page"}));
        const artItems=Object.values(artworks).filter(a=>!q||`${a.title} ${a.artist} ${a.era} ${a.roomName}`.toLowerCase().includes(q)).slice(0,10).map(a=>({label:a.title,sub:`${a.artist} · ${a.era}`,artId:a.id,type:"art"}));
        current=[...pageItems,...artItems].slice(0,12); activeIndex=0;
        if(results){results.innerHTML=current.map((item,i)=>`<button type="button" class="${i===0?'active':''}" data-command-index="${i}"><span>${item.type==='art'?'ART':'PAGE'}</span><strong>${item.label}</strong><small>${item.sub}</small></button>`).join("");results.querySelectorAll("button").forEach((b,i)=>b.addEventListener("click",()=>activate(i)));}
    };
    const activate=i=>{
        const item=current[i]; if(!item)return;
        close();
        if(item.type==="page"){window.location.href=item.url;return;}
        if(document.body.dataset.page==="exhibitions") openFromExplorer(item.artId);
        else window.location.href=`exhibitions.html?art=${encodeURIComponent(item.artId)}`;
    };
    trigger.addEventListener("click",open); getElement("commandClose")?.addEventListener("click",close); wrap.querySelector(".command-backdrop")?.addEventListener("click",close);
    input?.addEventListener("input",()=>render(input.value));
    document.addEventListener("keydown",e=>{
        if((e.ctrlKey||e.metaKey)&&e.key.toLowerCase()==="k"){e.preventDefault();wrap.classList.contains("open")?close():open();return;}
        if(!wrap.classList.contains("open")) return;
        if(e.key==="Escape"){e.preventDefault();close();}
        if(e.key==="ArrowDown"){e.preventDefault();select(activeIndex+1);}
        if(e.key==="ArrowUp"){e.preventDefault();select(activeIndex-1);}
        if(e.key==="Enter"){e.preventDefault();activate(activeIndex);}
    });
}

